import assert from "node:assert/strict";
import fs from "node:fs";
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),"utf8");
const html=read("public/ronda/index.html"), app=read("public/ronda/app.js"), mesa=read("public/ronda/editorial-mesa.js"), production=read("public/ronda/production-view.js"), shell=read("src/ronda/shell.js"), platform=read("src/index.js");
assert.match(html,/id="navNewsroom"[\s\S]{0,120}<span>Mesa<\/span>/);
assert.match(html,/id="navProduction"[\s\S]{0,120}<span>Produção<\/span>/);
assert.match(html,/id="newsroomView"/); assert.match(html,/id="productionView"/);
assert.match(app,/productionView\.hidden = view !== "production"/);
assert.match(app,/showView\("newsroom"\); loadNewsroom\(\)/); assert.match(app,/showView\("production"\)/);
for(const label of ['Saúde das fontes','Assuntos em aceleração','Desde a última ronda','Alertas editoriais']) assert.ok(mesa.includes(label),`Mesa sem ${label}`);
assert.match(production,/getElementById\('productionView'\)/); assert.match(production,/set_comment/);
